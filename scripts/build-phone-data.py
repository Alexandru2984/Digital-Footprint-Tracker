#!/usr/bin/env python3
"""Generates Sources/App/Services/PhoneData.swift from Google's libphonenumber.

The offline phone lookup (country, region, original carrier) needs no API key.
Its data comes from libphonenumber's public resources at a pinned release:
  - PhoneNumberMetadata.xml: which countries share a calling code;
  - geocoding/en/*.txt: the region a prefix was assigned to, kept to three
    digits after the calling code (North America: per area code, by state);
  - carrier/en/*.txt: the carrier a mobile range was first allocated to.

Usage: scripts/build-phone-data.py [release-tag]
"""
import collections
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

TAG = sys.argv[1] if len(sys.argv) > 1 else "v9.0.41"
RAW = f"https://raw.githubusercontent.com/google/libphonenumber/{TAG}/"
OUT = Path(__file__).resolve().parent.parent / "Sources/App/Services/PhoneData.swift"

US_STATES = {
    "AL": "Alabama", "AK": "Alaska", "AZ": "Arizona", "AR": "Arkansas", "CA": "California", "CO": "Colorado",
    "CT": "Connecticut", "DE": "Delaware", "DC": "District of Columbia", "FL": "Florida", "GA": "Georgia",
    "HI": "Hawaii", "ID": "Idaho", "IL": "Illinois", "IN": "Indiana", "IA": "Iowa", "KS": "Kansas",
    "KY": "Kentucky", "LA": "Louisiana", "ME": "Maine", "MD": "Maryland", "MA": "Massachusetts",
    "MI": "Michigan", "MN": "Minnesota", "MS": "Mississippi", "MO": "Missouri", "MT": "Montana",
    "NE": "Nebraska", "NV": "Nevada", "NH": "New Hampshire", "NJ": "New Jersey", "NM": "New Mexico",
    "NY": "New York", "NC": "North Carolina", "ND": "North Dakota", "OH": "Ohio", "OK": "Oklahoma",
    "OR": "Oregon", "PA": "Pennsylvania", "RI": "Rhode Island", "SC": "South Carolina", "SD": "South Dakota",
    "TN": "Tennessee", "TX": "Texas", "UT": "Utah", "VT": "Vermont", "VA": "Virginia", "WA": "Washington",
    "WV": "West Virginia", "WI": "Wisconsin", "WY": "Wyoming", "PR": "Puerto Rico",
}


def fetch(path):
    with urllib.request.urlopen(RAW + path, timeout=60) as response:
        return response.read().decode("utf-8")


def entries(text):
    for line in text.splitlines():
        if not line or line.startswith("#") or "|" not in line:
            continue
        prefix, value = line.split("|", 1)
        if prefix.isdigit() and value.strip():
            yield prefix, value.strip()


def main():
    metadata = ET.fromstring(fetch("resources/PhoneNumberMetadata.xml"))
    codes = collections.defaultdict(list)
    for territory in metadata.iter("territory"):
        region, code = territory.get("id"), territory.get("countryCode")
        if not region or not code or region == "001":
            continue
        if territory.get("mainCountryForCode") == "true":
            codes[code].insert(0, region)
        else:
            codes[code].append(region)

    with ThreadPoolExecutor(16) as pool:
        geo_texts = dict(zip(codes, pool.map(lambda c: safe(f"resources/geocoding/en/{c}.txt"), codes)))
        carrier_names = [f"{code}{d}" for code in codes for d in [""] + [str(i) for i in range(10)]]
        carrier_texts = dict(zip(carrier_names,
                                 pool.map(lambda n: safe(f"resources/carrier/en/{n}.txt"), carrier_names)))

    geo = {}
    for code, text in geo_texts.items():
        if not text:
            continue
        rows = dict(entries(text))
        if code == "1":
            # North America: one state or province per area code.
            states = collections.defaultdict(collections.Counter)
            for prefix, place in rows.items():
                if len(prefix) >= 7:
                    state = place.rsplit(", ", 1)[-1]
                    states[prefix[:4]][US_STATES.get(state, state)] += 1
            for npa, counter in states.items():
                geo[npa] = counter.most_common(1)[0][0]
            for prefix, place in rows.items():
                if len(prefix) == 4:
                    geo[prefix] = place
        else:
            for prefix, place in rows.items():
                if len(prefix) <= len(code) + 3:
                    geo[prefix] = place

    carriers = {}
    for text in carrier_texts.values():
        for prefix, carrier in entries(text or ""):
            carriers[prefix] = carrier

    def block(rows):
        lines = [f"{k}|{v}" for k, v in sorted(rows.items())]
        body = "\n".join(lines)
        assert '"""#' not in body
        return body

    swift = f'''// Generated by scripts/build-phone-data.py from libphonenumber {TAG}. Do not edit.
// Data: Copyright (C) Google Inc., Apache License 2.0.

enum PhoneData {{
    static let release = "{TAG}"

    /// `code|REGION,REGION…`, the code's main country first.
    static let callingCodes = #"""
{block({c: ",".join(r) for c, r in codes.items()})}
"""#

    /// `prefix|region`, the calling code included.
    static let regions = #"""
{block(geo)}
"""#

    /// `prefix|carrier` the range was allocated to.
    static let carriers = #"""
{block(carriers)}
"""#
}}
'''
    OUT.write_text(swift)
    print(f"{OUT}: {len(codes)} calling codes, {len(geo)} regions, {len(carriers)} carrier ranges, "
          f"{OUT.stat().st_size // 1024} KiB")


def safe(path):
    try:
        return fetch(path)
    except Exception:  # most code/digit combinations have no file
        return None


if __name__ == "__main__":
    main()
